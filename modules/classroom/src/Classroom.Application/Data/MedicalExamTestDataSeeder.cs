    private async Task CreateQuizAsync(string name, string description, IReadOnlyList<Question> questions)
    {
        var quiz = new Quiz(Guid.NewGuid(), name, description, null);
        quiz.SetQuestions(questions.Select(q => new QuizQuestion(Guid.NewGuid(), q.Id, 0)).ToList());
        await _quizRepository.InsertAsync(quiz, autoSave: true);
    }

    /// <summary>创建单选题。</summary>
    private static Question Sc(
        string stem,
        string optionA,
        string optionB,
        string optionC,
        string optionD,
        string answer,
        string explanation) =>
        new(Guid.NewGuid(), QuestionType.SingleChoice, stem,
            new List<QuestionOption>
            {
                new("A", optionA), new("B", optionB), new("C", optionC), new("D", optionD),
            },
            answer, explanation);

    /// <summary>创建多选题。</summary>
    private static Question Mc(
        string stem,
        IReadOnlyList<string> optionTexts,
        string answer,
        string explanation)
    {
        const string keys = "ABCDEFGH";
        return new(Guid.NewGuid(), QuestionType.MultipleChoice, stem,
            optionTexts.Select((text, i) => new QuestionOption(keys[i].ToString(), text)).ToList(),
            answer, explanation);
    }
